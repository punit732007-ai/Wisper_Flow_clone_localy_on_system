class ThemeManager:
    """Central singleton managing built-in and user-custom themes."""

    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
            cls._instance._initialized = False
        return cls._instance

    def __init__(self):
        if getattr(self, "_initialized", False):
            return
        self._initialized = True

        self._themes: Dict[str, Dict[str, Any]] = json.loads(json.dumps(BUILTIN_THEMES))
        self._current_theme_key: str = "default_dark"
        self._custom_theme: Dict[str, Any] = {}
        self._callbacks: List[Callable[[], None]] = []

        self._load_from_config()

    def _load_from_config(self) -> None:
        """Load saved theme and custom overrides from global config."""
        saved_theme = config.get("app_theme", "default_dark")
        custom_saved = config.get("custom_theme", {})

        if isinstance(custom_saved, dict) and custom_saved:
            self._custom_theme = custom_saved
            # Register or update custom theme in catalog
            custom_merged = dict(BUILTIN_THEMES["default_dark"])
            custom_merged.update({
                "name": "Custom Theme",
                "category": "Custom",
                "description": "User-crafted personalized color scheme, layout, and wallpaper.",
            })
            custom_merged.update(self._custom_theme)
            self._themes["custom"] = custom_merged

        if saved_theme in self._themes:
            self._current_theme_key = saved_theme
        else:
            self._current_theme_key = "default_dark"

    def save_to_config(self) -> None:
        """Persist active theme and custom overrides to disk."""
        config.set("app_theme", self._current_theme_key, auto_save=False)
        if self._custom_theme:
            config.set("custom_theme", self._custom_theme, auto_save=False)
        config.save()

    @property
    def current_theme(self) -> Dict[str, Any]:
        """Return the dictionary of colors and styles for the currently active theme."""
        return self._themes.get(self._current_theme_key, self._themes["default_dark"])

    @property
    def current_theme_key(self) -> str:
        """Return the key identifier of active theme."""
        return self._current_theme_key

    @property
    def all_themes(self) -> Dict[str, Dict[str, Any]]:
        """Return all available themes dictionary."""
        return self._themes

    def get_themes_by_category(self) -> Dict[str, List[str]]:
        """Group theme keys by their category."""
        grouped: Dict[str, List[str]] = {}
        for key, th in self._themes.items():
            cat = th.get("category", "Modern UI")
            if cat not in grouped:
                grouped[cat] = []
            grouped[cat].append(key)
        return grouped

    def set_theme(self, key: str, auto_save: bool = True) -> None:
        """Switch to a different theme and notify registered listeners."""
        if key in self._themes:
            self._current_theme_key = key
            if auto_save:
                self.save_to_config()
            self._notify()

    def set_custom_theme(self, overrides: Dict[str, Any], auto_save: bool = True) -> None:
        """Update the custom theme dictionary, activate it, and notify."""
        self._custom_theme.update(overrides)
        custom_merged = dict(BUILTIN_THEMES["default_dark"])
        custom_merged.update({
            "name": "Custom Theme",
            "category": "Custom",
            "description": "User-crafted personalized color scheme, layout, and wallpaper.",
        })
        custom_merged.update(self._custom_theme)
        self._themes["custom"] = custom_merged
        self.set_theme("custom", auto_save=auto_save)

    def register_callback(self, cb: Callable[[], None]) -> None:
        """Register a function to be called when the theme changes."""
        if cb not in self._callbacks:
            self._callbacks.append(cb)

    def _notify(self) -> None:
        """Invoke all theme change callbacks."""
        for cb in self._callbacks:
            try:
                cb()
            except Exception as e:
                print(f"[ThemeManager] Error in theme callback: {e}")

    def get_color(self, color_key: str, default: str = "#ffffff") -> str:
        """Convenience method to get a color from the current theme."""
        return self.current_theme.get(color_key, default)


